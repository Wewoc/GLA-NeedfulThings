#!/usr/bin/env python3
"""
quick_dash.py — Quick Dashboard Builder
Part of: GLA-Tools

Builds a throw-away GLA dashboard specialist from quick_config.json.
No LLM involved — deterministic assembly from fixed code blocks.

Usage:
    python quick_dash.py              # build specialist from quick_config.json
    python quick_dash.py --fields     # print available fields as JSON (used by config.ps1)
"""

import sys
import json
import time
import subprocess
from pathlib import Path
from datetime import date, timedelta

CONFIG_FILE = Path(__file__).parent / "quick_config.json"

# ══════════════════════════════════════════════════════════════════════════════
#  GLA import helper
# ══════════════════════════════════════════════════════════════════════════════

def _load_config() -> dict:
    if not CONFIG_FILE.exists():
        print("[Error] quick_config.json not found. Run config.ps1 first.")
        sys.exit(1)
    return json.loads(CONFIG_FILE.read_text(encoding="utf-8"))


def _import_gla_maps(gla_path: str):
    gla = Path(gla_path)
    if not gla.exists():
        print(f"[Error] GLA path not found: {gla_path}")
        sys.exit(1)
    if str(gla) not in sys.path:
        sys.path.insert(0, str(gla))
    try:
        from maps import field_map, context_map
        return field_map, context_map
    except ImportError as e:
        print(f"[Error] GLA modules not importable: {e}")
        sys.exit(1)


# ══════════════════════════════════════════════════════════════════════════════
#  Field classification
# ══════════════════════════════════════════════════════════════════════════════

def _classify_fields(gla_path: str, mode: str) -> dict:
    """
    Return available fields split by type.
    mode: "intraday" or "overview"
    """
    field_map, context_map = _import_gla_maps(gla_path)

    # Import garmin_map directly to inspect field definitions
    from maps import garmin_map

    garmin_daily   = []
    garmin_intraday = []

    for f in field_map.list_fields():
        defn = garmin_map._FIELD_MAP.get(f, {})
        has_intraday = defn.get("intraday") is not None
        has_daily    = defn.get("daily") is not None or defn.get("raw_pct") is not None
        if mode == "intraday" and has_intraday:
            garmin_intraday.append(f)
        elif mode == "overview" and has_daily:
            garmin_daily.append(f)

    context_fields = []
    for source in context_map.list_sources():
        for f in context_map.list_fields(source):
            context_fields.append({"field": f, "source": source})

    return {
        "garmin":  garmin_intraday if mode == "intraday" else garmin_daily,
        "context": context_fields,
    }


# ══════════════════════════════════════════════════════════════════════════════
#  --fields: print available fields as JSON for config.ps1
# ══════════════════════════════════════════════════════════════════════════════

def cmd_fields():
    cfg  = _load_config()
    mode = cfg.get("mode", "overview")
    gla  = cfg.get("gla_path", "")
    fields = _classify_fields(gla, mode)
    print(json.dumps(fields))


# ══════════════════════════════════════════════════════════════════════════════
#  Code block library — fixed patterns, no generation
