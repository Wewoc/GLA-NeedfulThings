def _label(field: str) -> str:
    return field.replace("_", " ").title()

def _unit(field: str) -> str:
    return _UNITS.get(field, "")

def _group(field: str, context_fields: list) -> str:
    ctx_names = {f["field"]: f["source"] for f in context_fields}
    return ctx_names.get(field, "garmin")


# ══════════════════════════════════════════════════════════════════════════════
#  Assemble specialist
# ══════════════════════════════════════════════════════════════════════════════

def _assemble(cfg: dict, timestamp: int) -> str:
    name        = cfg["name"]
    description = cfg.get("description", "")
    mode        = cfg["mode"]
    formats     = cfg["formats"]
    garmin_sel  = cfg["garmin_fields"]
    context_sel = cfg["context_fields"]

    filename   = f"quick_{timestamp}_dash.py"
    field_list = ", ".join(garmin_sel + context_sel)

    needs_context = bool(context_sel)
    needs_garmin  = bool(garmin_sel)

    source_parts = []
    if needs_garmin:
        source_parts.append("Garmin")
    if needs_context:
        source_parts.append("context_data/")
    source = " + ".join(source_parts)

    gla_path_escaped = cfg.get("gla_path", "").replace("\\", "\\\\")
    code = _HEADER.format(
        filename=filename,
        mode=mode,
        field_list=field_list,
        gla_path=gla_path_escaped,
    )

    if needs_garmin:
        code += _IMPORT_FIELD_MAP
    if needs_context:
        code += _IMPORT_CONTEXT_MAP

    fmt_lines = _format_lines(formats, timestamp)
    code += _META.format(
        name=name,
        description=description,
        source=source,
        formats=fmt_lines,
    )

    if needs_garmin:
        entries = ""
        for f in garmin_sel:
            entries += (
                f'    {{"field": "{f}", '
                f'"label": "{_label(f)}", '
                f'"unit": "{_unit(f)}", '
                f'"group": "garmin"}},\n'
            )
        code += _GARMIN_FIELDS_DECL.format(entries=entries)

    if needs_context:
        entries = ""
        for f in context_sel:
            grp = _group(f, cfg.get("_context_meta", []))
            entries += (
                f'    {{"field": "{f}", '
                f'"label": "{_label(f)}", '
                f'"unit": "{_unit(f)}", '
                f'"group": "{grp}"}},\n'
            )
        code += _CONTEXT_FIELDS_DECL.format(entries=entries)

    if mode == "intraday":
        build_block = _BUILD_INTRADAY
    else:
        build_block = _BUILD_OVERVIEW

    # Inject title — replace placeholder
    build_block = build_block.replace("{title}", name)

    # Remove context loop if not needed
    if not needs_context and "_CONTEXT_FIELDS" in build_block:
        # Strip the context for-loop block
        lines = build_block.splitlines()
        out, skip = [], False
        for line in lines:
            if "for f in _CONTEXT_FIELDS:" in line:
                skip = True
            if skip and line.strip() == "" and not any(
                "for f in _CONTEXT_FIELDS" in l for l in lines
            ):
                skip = False
                continue
            if not skip:
                out.append(line)
        build_block = "\n".join(out)

    # Remove garmin loop if not needed
    if not needs_garmin and "_GARMIN_FIELDS" in build_block:
        lines = build_block.splitlines()
        out, skip = [], False
        for line in lines:
            if "for f in _GARMIN_FIELDS:" in line:
                skip = True
            if skip and line.strip() == "":
                skip = False
                continue
            if not skip:
                out.append(line)
        build_block = "\n".join(out)

    code += build_block
    return code


# ══════════════════════════════════════════════════════════════════════════════
#  Build
# ══════════════════════════════════════════════════════════════════════════════

def cmd_build():
    cfg = _load_config()

    output_dir = Path(__file__).parent / "scripts"
    output_dir.mkdir(parents=True, exist_ok=True)

    timestamp = int(time.time())
    code      = _assemble(cfg, timestamp)

    out_path = output_dir / f"quick_{timestamp}_dash.py"
    out_path.write_text(code, encoding="utf-8")

    print(f"[OK] Specialist written: {out_path.name}")

    # Hand off to quick_run.py
    runner = Path(__file__).parent / "quick_run.py"
    subprocess.run([sys.executable, str(runner)])


# ══════════════════════════════════════════════════════════════════════════════
#  Entry point
# ══════════════════════════════════════════════════════════════════════════════

if __name__ == "__main__":
    arg = sys.argv[1] if len(sys.argv) > 1 else None
    if arg == "--fields":
        cmd_fields()
    elif arg is None:
        cmd_build()
    else:
        print(f"[Error] Unknown argument: {arg}")
        print("Usage: python quick_dash.py [--fields]")
        sys.exit(1)
