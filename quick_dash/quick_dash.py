_HEADER = '''\
#!/usr/bin/env python3
"""
{filename}

Quick specialist — generated by GLA-Tools/quick_dash.
Mode: {mode}
Fields: {field_list}
"""

import sys
from pathlib import Path

sys.path.insert(0, r"{gla_path}")
'''

_IMPORT_FIELD_MAP = "from maps.field_map   import get as field_get\n"
_IMPORT_CONTEXT_MAP = "from maps.context_map import get as context_get\n"

_META = '''
META = {{
    "name":        "{name}",
    "description": "{description}",
    "source":      "{source}",
    "formats": {{
{formats}
    }},
}}

'''

_GARMIN_FIELDS_DECL = "_GARMIN_FIELDS = [\n{entries}]\n\n"
_CONTEXT_FIELDS_DECL = "_CONTEXT_FIELDS = [\n{entries}]\n\n"

_BUILD_OVERVIEW = '''\
def build(date_from: str, date_to: str, settings: dict) -> dict:
    fields_out = []

    for f in _GARMIN_FIELDS:
        result = field_get(f["field"], date_from, date_to, resolution="daily")
        garmin = result.get("garmin", {})
        days = [
            {"date": entry["date"], "value": entry["value"]}
            for entry in garmin.get("values", [])
        ]
        fields_out.append({
            "field": f["field"],
            "label": f["label"],
            "unit":  f["unit"],
            "group": f["group"],
            "days":  days,
        })

    for f in _CONTEXT_FIELDS:
        result = context_get(f["field"], date_from, date_to)
        source_result = next(iter(result.values()), {}) if result else {}
        days = [
            {"date": entry["date"], "value": entry["value"]}
            for entry in source_result.get("values", [])
        ]
        fields_out.append({
            "field": f["field"],
            "label": f["label"],
            "unit":  f["unit"],
            "group": f["group"],
            "days":  days,
        })

    return {
        "title":    "{title}",
        "subtitle": f"{date_from} \\u2192 {date_to}",
        "date_from": date_from,
        "date_to":   date_to,
        "fields":   fields_out,
    }
'''

_BUILD_INTRADAY = '''\
def build(date_from: str, date_to: str, settings: dict) -> dict:
    fields_out = []

    for f in _GARMIN_FIELDS:
        result = field_get(f["field"], date_from, date_to, resolution="intraday")
        garmin = result.get("garmin", {})
        series_raw = []
        for day_entry in garmin.get("values", []):
            day_series = day_entry.get("series")
            if isinstance(day_series, list):
                series_raw.extend(day_series)

        # Hourly aggregation for HTML/JSON — average per hour
        hourly = {}
        for entry in series_raw:
            hour_key = entry["ts"][:13]  # "2026-04-04T14"
            if hour_key not in hourly:
                hourly[hour_key] = []
            hourly[hour_key].append(entry["value"])
        days = [
            {"date": f"{h}:00:00", "value": round(sum(v) / len(v), 1)}
            for h, v in sorted(hourly.items())
        ]

        # series_hourly: aggregated for HTML timeseries chart
        series_hourly = [
            {"ts": f"{h}:00:00", "value": round(sum(v) / len(v), 1)}
            for h, v in sorted(hourly.items())
        ]

        fields_out.append({
            "field":  f["field"],
            "label":  f["label"],
            "unit":   f["unit"],
            "group":  f["group"],
            "series": series_hourly,  # hourly -- for HTML timeseries chart
            "series_raw": series_raw, # raw    -- for Excel
        })

    return {
        "title":    "{title}",
        "subtitle": f"{date_from} \\u2192 {date_to}",
        "date_from": date_from,
        "date_to":   date_to,
        "fields":   fields_out,
    }
'''

# ══════════════════════════════════════════════════════════════════════════════
#  Format → filename + META entry helpers
# ══════════════════════════════════════════════════════════════════════════════

_FORMAT_EXT = {
    "html":         ".html",
    "html_complex": ".html",
    "html_mobile":  ".html",
    "excel":        ".xlsx",
    "json":         ".json",
    "pdf":          ".pdf",
    "word":         ".docx",
}

def _format_lines(formats: list, timestamp: int) -> str:
    lines = []
    for fmt in formats:
        ext = _FORMAT_EXT.get(fmt, ".html")
        lines.append(f'        "{fmt}": "quick_{timestamp}_{fmt}{ext}",')
    return "\n".join(lines)


